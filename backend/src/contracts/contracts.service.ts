import { Injectable, NotFoundException } from '@nestjs/common';
import { PrismaService } from '../prisma/prisma.service';

@Injectable()
export class ContractsService {
  constructor(private prisma: PrismaService) {}

  async generate(agencyId: string, bookingId: string) {
    const booking = await this.prisma.booking.findFirst({
      where: { id: bookingId, agencyId },
      include: { car: true, customer: true, agency: true },
    });

    if (!booking) throw new NotFoundException('Booking not found');

    const content = `
      <div style="font-family: sans-serif; padding: 40px; color: #1e293b;">
        <h1 style="font-size: 24px; font-weight: 900; text-transform: uppercase; margin-bottom: 40px;">Rental Agreement: ${booking.agency.name}</h1>
        
        <div style="display: grid; grid-template-columns: 1fr 1fr; gap: 40px; margin-bottom: 40px;">
          <div>
            <h3 style="font-size: 10px; font-weight: 900; color: #64748b; text-transform: uppercase;">Lessor (Agency)</h3>
            <p style="font-weight: 700;">${booking.agency.name}</p>
            <p style="font-size: 12px; color: #64748b;">${booking.agency.contactEmail}</p>
          </div>
          <div>
            <h3 style="font-size: 10px; font-weight: 900; color: #64748b; text-transform: uppercase;">Lessee (Customer)</h3>
            <p style="font-weight: 700;">${booking.customer.firstName} ${booking.customer.lastName}</p>
            <p style="font-size: 12px; color: #64748b;">ID: ${booking.customer.identityNumber} (${booking.customer.identityType})</p>
          </div>
        </div>

        <div style="background: #f8fafc; padding: 24px; border-radius: 16px; margin-bottom: 40px;">
          <h3 style="font-size: 10px; font-weight: 900; color: #64748b; text-transform: uppercase; margin-bottom: 16px;">Vehicle Details</h3>
          <p style="font-size: 18px; font-weight: 900;">${booking.car.brand} ${booking.car.model}</p>
          <p style="font-size: 14px; font-weight: 700; color: #3b82f6;">Plate: ${booking.car.licensePlate}</p>
        </div>

        <div style="margin-bottom: 40px;">
          <h3 style="font-size: 10px; font-weight: 900; color: #64748b; text-transform: uppercase; margin-bottom: 16px;">Rental Terms</h3>
          <p style="font-size: 14px; line-height: 1.6;">
            1. The rental period starts on <strong>${booking.startDate.toLocaleDateString()}</strong> and ends on <strong>${booking.endDate.toLocaleDateString()}</strong>.<br/>
            2. Total rental amount is <strong>${booking.totalPrice} MAD</strong> (Including 20% VAT).<br/>
            3. The lessee agrees to return the vehicle in the same condition as received.
          </p>
        </div>
        
        <div style="border-top: 1px solid #e2e8f0; padding-top: 40px; margin-top: 40px;">
          <p style="font-size: 10px; color: #94a3b8; font-style: italic;">Digitally generated by CarHub OS on ${new Date().toLocaleString()}</p>
        </div>
      </div>
    `;

    return this.prisma.contract.create({
      data: {
        content,
        bookingId,
        agencyId,
        status: 'SENT',
      },
    });
  }

  async sign(id: string, signatureData: string) {
    return this.prisma.contract.update({
      where: { id },
      data: {
        signatureData,
        signedAt: new Date(),
        status: 'SIGNED',
      },
    });
  }

  async findOne(id: string) {
    return this.prisma.contract.findUnique({
      where: { id },
      include: {
        booking: { include: { car: true, customer: true } },
        agency: true,
      },
    });
  }
}
